"""
Prediction report generator for CauliCare.
Formats detailed agronomic inspection reports for download.
"""

from typing import Dict, Any
from config.settings import DISEASE_INFO, RESEARCH_PAPER_URL, DATASET_SOURCE_URL


def generate_text_report(result: Dict[str, Any], uploaded_filename: str = "leaf_image.jpg") -> str:
    """
    Generates a clean, professional text report for field agronomic records.
    Only called when a real prediction result is present.
    """
    predicted_class = result.get("predicted_class", "Unknown")
    confidence_pct = result.get("confidence_pct", 0.0)
    model_name = result.get("model_name", "Unknown")
    timestamp = result.get("timestamp", "N/A")
    latency = result.get("inference_time_ms", "N/A")
    probs = result.get("probabilities", {})

    info = DISEASE_INFO.get(predicted_class, {})
    title = info.get("title", predicted_class)
    severity = info.get("severity", "N/A")
    urgency = info.get("urgency", "N/A")
    overview = info.get("overview", "")
    symptoms = info.get("symptoms", [])
    recommendations = info.get("recommendations", [])

    symptoms_text = "\n".join(f"  - {s}" for s in symptoms)
    recs_text = "\n".join(f"  {idx+1}. {r}" for idx, r in enumerate(recommendations))
    probs_text = "\n".join(f"  - {cls}: {score*100:.2f}%" for cls, score in probs.items())

    report = f"""================================================================================
                    CAULICARE - CROP HEALTH INSPECTION REPORT
================================================================================

1. INSPECTION METADATA
--------------------------------------------------------------------------------
Timestamp:            {timestamp}
Source Image:         {uploaded_filename}
Analyzed Model:       {model_name}
Inference Latency:    {latency} ms
Report Generated By:  CauliCare Agricultural Diagnostic System

2. CLASSIFICATION DIAGNOSIS
--------------------------------------------------------------------------------
Primary Condition:    {predicted_class} ({title})
Model Confidence:     {confidence_pct:.2f}%
Assessed Severity:    {severity}
Management Urgency:   {urgency}

3. CLASS PROBABILITY SPECTRUM
--------------------------------------------------------------------------------
{probs_text}

4. CONDITION OVERVIEW & ETIOLOGY
--------------------------------------------------------------------------------
{overview}

5. FIELD SYMPTOMS
--------------------------------------------------------------------------------
{symptoms_text}

6. RECOMMENDED AGRONOMIC PROTOCOLS
--------------------------------------------------------------------------------
{recs_text}

7. SCIENTIFIC ATTRIBUTION & SOURCES
--------------------------------------------------------------------------------
Research Paper:       {RESEARCH_PAPER_URL}
Dataset Reference:    {DATASET_SOURCE_URL}

NOTE:
This diagnostic output is generated by a computer vision model trained on
cauliflower leaf imagery. For large-scale disease outbreaks or confirmation,
consult certified regional crop protection officers and agricultural extension
pathology laboratories.
================================================================================
"""
    return report
